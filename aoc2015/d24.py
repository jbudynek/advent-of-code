# Algorithm (code written by Claude, an AI assistant made by Anthropic):
# Split the packages into k groups of equal weight (target = total / k), where the
# first group must have as few packages as possible, then the smallest product
# (quantum entanglement, QE).
# - Part 1 (k = 3): for group-1 size n = 1, 2, 3, ... enumerate all subsets of n
#   packages (recursive generator with pruning on the remaining target weight)
#   whose sum is the target. A subset is valid only if the remaining packages can
#   themselves be split into k-1 groups of the target weight (checked recursively
#   with the same subset generator). The first size n with a valid subset wins;
#   the answer is the minimum product among the valid subsets of that size.
#   No itertools: subsets are generated by hand.
# - Part 2 (k = 4): same algorithm, only the number of groups changes (the target
#   weight becomes total / 4 and the rest must split into 3 groups).

ipt_test = """1
2
3
4
5
7
8
9
10
11"""

ipt_puzzle = open("input.txt").read().strip()


def parse(ipt):
    return sorted((int(x) for x in ipt.split()), reverse=True)


def subsets(w, size, target, start=0):
    """Yield tuples of indices (increasing) of `size` items of w summing to target."""
    if size == 0:
        if target == 0:
            yield ()
        return
    for i in range(start, len(w) - size + 1):
        if w[i] > target:
            continue
        for rest in subsets(w, size - 1, target - w[i], i + 1):
            yield (i,) + rest


def can_split(w, groups, target):
    if groups == 1:
        return True
    for size in range(1, len(w) + 1):
        for sub in subsets(w, size, target):
            rest = [x for i, x in enumerate(w) if i not in sub]
            if can_split(rest, groups - 1, target):
                return True
    return False


def best_qe(w, groups):
    target = sum(w) // groups
    for size in range(1, len(w) + 1):
        best = None
        for sub in subsets(w, size, target):
            qe = 1
            for i in sub:
                qe *= w[i]
            if best is not None and qe >= best:
                continue
            rest = [x for i, x in enumerate(w) if i not in sub]
            if can_split(rest, groups - 1, target):
                best = qe
        if best is not None:
            return best


# test
r_test1 = best_qe(parse(ipt_test), 3)
print(f"# Test part 1: {r_test1} (expected 99)")
assert r_test1 == 99

r_test2 = best_qe(parse(ipt_test), 4)
print(f"# Test part 2: {r_test2} (expected 44)")
assert r_test2 == 44

